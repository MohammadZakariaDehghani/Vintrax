import { mkdir, readFile, rm, rmdir, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import type { ConfigService } from '@nestjs/config';
import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  type S3Client,
} from '@aws-sdk/client-s3';
import type { Env } from '../../config/env';
import { createS3Client, s3PublicBaseUrl } from './storage.service';

export interface SaveOptions {
  contentType: string;
  /** Sent with the object where the backend supports it (S3). */
  cacheControl?: string;
}

/**
 * Where processed photos live, behind the four operations the image pipeline
 * needs and nothing else.
 *
 * Keys are always generated by Vintrax (`vehicles/<uuid>/640.webp`) — never
 * derived from anything a user sent — and every implementation still refuses
 * a key that could step outside its root.
 *
 * `LocalImageStorage` is what production runs today (STORAGE_DRIVER=local).
 * `S3ImageStorage` exists because the API already supported STORAGE_DRIVER=s3
 * before this pipeline and that deployment must keep working. The interface
 * is deliberately this small so a `GoogleCloudImageStorage` can be added for
 * the Google Cloud migration without touching `ImageProcessor` or
 * `VehicleImagesService`.
 */
export interface ImageStorage {
  save(key: string, data: Buffer, options: SaveOptions): Promise<void>;
  read(key: string): Promise<Buffer>;
  exists(key: string): Promise<boolean>;
  /** Idempotent: deleting a key that is not there succeeds. */
  delete(key: string): Promise<void>;
  /** The URL a browser fetches `key` from. */
  getPath(key: string): string;
  /** The inverse of `getPath`, or null for a URL this storage did not issue. */
  keyFromUrl(url: string): string | null;
}

/** Injection token for the configured `ImageStorage`. */
export const IMAGE_STORAGE = Symbol('IMAGE_STORAGE');

/** The implementation STORAGE_DRIVER selects. */
export function createImageStorage(config: ConfigService<Env, true>): ImageStorage {
  return config.get('STORAGE_DRIVER', { infer: true }) === 's3'
    ? new S3ImageStorage(
        createS3Client(config),
        config.get('S3_BUCKET', { infer: true }) ?? '',
        s3PublicBaseUrl(config),
      )
    : new LocalImageStorage(config.get('UPLOAD_DIR', { infer: true }));
}

const SAFE_KEY = /^[a-z0-9-]+(\/[A-Za-z0-9._-]+)+$/;

export function assertSafeKey(key: string): void {
  if (!SAFE_KEY.test(key) || key.split('/').some((part) => part === '.' || part === '..')) {
    throw new Error(`Refusing unsafe storage key "${key}"`);
  }
}

/** Files under the API's upload directory, served at `/uploads/<key>`. */
export class LocalImageStorage implements ImageStorage {
  private readonly root: string;

  constructor(root: string) {
    this.root = resolve(root);
  }

  async save(key: string, data: Buffer): Promise<void> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    // Write-then-rename would be atomic, but every key here is new: a reader
    // can only ask for it after the database says it exists, which is after
    // this resolves.
    await writeFile(path, data);
  }

  read(key: string): Promise<Buffer> {
    return readFile(this.pathFor(key));
  }

  async exists(key: string): Promise<boolean> {
    try {
      return (await stat(this.pathFor(key))).isFile();
    } catch {
      return false;
    }
  }

  async delete(key: string): Promise<void> {
    const path = this.pathFor(key);
    await rm(path, { force: true });
    // Tidy a per-photo folder (`vehicles/<uuid>/…`) once its last file is
    // gone — rmdir fails on a folder that still holds something, which is the
    // point. Never a top-level folder like `vehicles/` itself.
    if (key.split('/').length > 2) await rmdir(dirname(path)).catch(() => undefined);
  }

  getPath(key: string): string {
    assertSafeKey(key);
    return `/uploads/${key}`;
  }

  keyFromUrl(url: string): string | null {
    if (!url.startsWith('/uploads/') || url.startsWith('//')) return null;
    const key = url.slice('/uploads/'.length);
    try {
      assertSafeKey(key);
      return key;
    } catch {
      return null;
    }
  }

  /** Filesystem location, confirmed to sit inside the upload root. */
  pathFor(key: string): string {
    assertSafeKey(key);
    const path = resolve(this.root, key);
    if (!path.startsWith(`${this.root}${sep}`)) {
      throw new Error(`Refusing storage key outside the upload root: "${key}"`);
    }
    return path;
  }
}

/** Any S3-compatible bucket, for deployments already on STORAGE_DRIVER=s3. */
export class S3ImageStorage implements ImageStorage {
  private readonly base: string;

  constructor(
    private readonly client: S3Client,
    private readonly bucket: string,
    publicBaseUrl: string,
  ) {
    this.base = publicBaseUrl.replace(/\/$/, '');
  }

  async save(key: string, data: Buffer, options: SaveOptions): Promise<void> {
    assertSafeKey(key);
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: key,
        Body: data,
        ContentType: options.contentType,
        CacheControl: options.cacheControl,
      }),
    );
  }

  async read(key: string): Promise<Buffer> {
    assertSafeKey(key);
    const object = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    if (!object.Body) throw new Error(`Object ${key} has no body`);
    return Buffer.from(await object.Body.transformToByteArray());
  }

  async exists(key: string): Promise<boolean> {
    assertSafeKey(key);
    try {
      await this.client.send(new HeadObjectCommand({ Bucket: this.bucket, Key: key }));
      return true;
    } catch {
      return false;
    }
  }

  async delete(key: string): Promise<void> {
    assertSafeKey(key);
    // S3 DeleteObject already succeeds for a missing key.
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }

  getPath(key: string): string {
    assertSafeKey(key);
    return `${this.base}/${key}`;
  }

  keyFromUrl(url: string): string | null {
    if (!url.startsWith(`${this.base}/`)) return null;
    const key = url.slice(this.base.length + 1);
    try {
      assertSafeKey(key);
      return key;
    } catch {
      return null;
    }
  }
}
