/**
 * Extracts the vehicle-make logos Vintrax needs out of `simple-icons`.
 *
 * The package carries about 3,500 icons. Importing it at runtime to use
 * fifteen of them would ship the rest, so the paths are lifted here into a
 * generated module and the package stays a devDependency.
 *
 *   node scripts/generate-brand-logos.mjs
 *
 * Re-run it after adding a make to MAKES below, or after upgrading the
 * package. The output is committed, so a build never depends on this script.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const frontend = join(here, '..', 'frontend');

// Resolved from the frontend package, which is where simple-icons is a
// devDependency — pnpm does not hoist it to the workspace root.
const require = createRequire(pathToFileURL(join(frontend, 'package.json')));
const icons = require('simple-icons');

/**
 * Makes worth carrying a logo for: what the seed data holds, plus the rest of
 * the volume sellers in Canada. A make that is missing here still works — it
 * falls back to a lettermark — so this list is a nicety, not a contract.
 */
const MAKES = [
  'Acura', 'Audi', 'BMW', 'Buick', 'Cadillac', 'Chevrolet', 'Chrysler', 'Dodge',
  'Fiat', 'Ford', 'Genesis', 'GMC', 'Honda', 'Hyundai', 'Infiniti', 'Jaguar',
  'Jeep', 'Kia', 'Land Rover', 'Lexus', 'Lincoln', 'Mazda', 'Mercedes-Benz',
  'Mini', 'Mitsubishi', 'Nissan', 'Polestar', 'Porsche', 'Ram', 'Rivian',
  'Subaru', 'Tesla', 'Toyota', 'Volkswagen', 'Volvo',
];

/** simple-icons keys are `si` + the title with non-alphanumerics stripped. */
const keyFor = (make) => `si${make.replace(/[^A-Za-z0-9]/g, '')}`;

const found = [];
const missing = [];

for (const make of MAKES) {
  const icon = icons[keyFor(make)];
  if (!icon) {
    missing.push(make);
    continue;
  }
  // The package ships a whole <svg>; only the path data is wanted, since the
  // component supplies its own sizing, colour and accessible name.
  const path = /\sd="([^"]+)"/.exec(icon.svg)?.[1];
  if (!path) {
    missing.push(make);
    continue;
  }
  found.push({ make, title: icon.title, path });
}

const body = found
  .map(({ make, title, path }) => `  ${JSON.stringify(make.toLowerCase())}: {\n    title: ${JSON.stringify(title)},\n    path: ${JSON.stringify(path)},\n  },`)
  .join('\n');

const out = `/**
 * Vehicle make logos, generated by scripts/generate-brand-logos.mjs.
 *
 * Do not edit by hand — re-run the script instead.
 *
 * Paths come from simple-icons (CC0-1.0). The marks themselves are the
 * trademarks of their respective owners and appear here only to label links to
 * that maker's own vehicles in Vintrax's inventory, which is what the mark is
 * for. Nothing here implies endorsement by, or affiliation with, any maker.
 *
 * Every path is drawn in a 24x24 viewBox.
 */
export interface BrandLogo {
  title: string;
  path: string;
}

export const BRAND_LOGOS: Record<string, BrandLogo> = {
${body}
};
`;

const target = join(frontend, 'src', 'components', 'brand-logos.generated.ts');
writeFileSync(target, out);

console.log(`${found.length} logos written to ${target}`);
if (missing.length) {
  console.log(`no icon in simple-icons for: ${missing.join(', ')} — these fall back to a lettermark`);
}
